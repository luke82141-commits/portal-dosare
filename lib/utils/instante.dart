/// "JudecatoriaSECTORUL1BUCURESTI" -> "Judecătoria Sectorul 1 București".
///
/// Pentru un cod necunoscut (instanță nou-înființată) desparte măcar tipul de
/// localitate, ca numele să nu rămână lipit.
String numeInstanta(String cod) {
  final c = cod.trim();
  if (c.isEmpty || c.contains(' ')) return c;

  final lower = c.toLowerCase();
  for (final (prefix, tip) in _tipuri) {
    if (!lower.startsWith(prefix)) continue;
    final rest = c.substring(prefix.length);
    if (rest.isEmpty) return tip;
    return '$tip ${_localitati[rest.toUpperCase()] ?? _capitalizeaza(rest)}';
  }
  return _localitati[c.toUpperCase()] ?? c;
}

String _capitalizeaza(String s) =>
    s[0].toUpperCase() + s.substring(1).toLowerCase();

